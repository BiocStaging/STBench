# Quality-control metrics


#' Add quality-control metrics
#'
#' Calculate basic spot-level and gene-level quality-control
#' metrics from raw counts in a SpatialExperiment object.
#'
#' Spot-level metrics include library size, log library size,
#' number of detected genes, and mitochondrial proportion.
#'
#' Gene-level metrics include mean expression and log mean
#' expression.
#'
#' @param spe A SpatialExperiment object.
#' @param assay_name Name of assay containing raw counts.
#'   Default is `"counts"`.
#' @param mito_pattern Regular expression used to identify
#'   mitochondrial genes from row names. Default is `"^MT-"`.
#'
#' @return A SpatialExperiment object with QC metrics added to
#'   `colData()` and `rowData()`.
#' @examples
#' data(spe_example)
#'
#' spe_qc <- add_qcs(
#'   spe_example,
#'   assay_name = "counts",
#'   mito_pattern = "^MT-"
#' )
#' #' @import sparseMatrixStats
#' @export
add_qcs <- function(
  spe,
  assay_name = "counts",
  mito_pattern = "^MT-"
) {
  # Check assay


  if (
    !assay_name %in%
      SummarizedExperiment::assayNames(spe)
  ) {
    stop(
      "Assay '",
      assay_name,
      "' was not found."
    )
  }


  # Counts


  counts_mat <- SummarizedExperiment::assay(
    spe,
    assay_name
  )


  # SPOT-LEVEL QC


  spe$library_size <-
    MatrixGenerics::colSums2(
      counts_mat
    )


  spe$log_library_size <-
    log(
      spe$library_size + 1
    )


  spe$detected_genes <-
    MatrixGenerics::colSums2(
      counts_mat > 0
    )


  # GENE-LEVEL QC


  SummarizedExperiment::rowData(spe)$gene_mean <-
    MatrixGenerics::rowMeans2(
      counts_mat
    )


  SummarizedExperiment::rowData(spe)$log_gene_mean <-
    log(
      SummarizedExperiment::rowData(
        spe
      )$gene_mean + 1
    )


  # MITOCHONDRIAL PROPORTION


  is_mito <- grepl(
    mito_pattern,
    rownames(spe),
    ignore.case = TRUE
  )


  if (any(is_mito)) {
    mito_counts <-
      MatrixGenerics::colSums2(
        counts_mat[
          is_mito, ,
          drop = FALSE
        ]
      )
  } else {
    mito_counts <- rep(
      0,
      ncol(spe)
    )

    warning(
      "No mitochondrial genes matched '",
      mito_pattern,
      "'.",
      call. = FALSE
    )
  }


  spe$mito_fraction <-
    mito_counts /
      pmax(
        spe$library_size,
        1
      )


  return(spe)
}


# Quality-control plots


#' Plot quality-control distributions
#'
#' Plot distributions of the main spot-level and gene-level
#' QC metrics stored in a SpatialExperiment object.
#'
#' The function can be used before or after filtering.
#'
#' @param spe A SpatialExperiment object containing QC metrics
#'   generated by `add_qcs()`.
#' @param bins Number of histogram bins. Default is 45.
#' @param show_density Logical. If TRUE, density curves are
#'   added to the histograms.
#' @param theme_name Plot theme. One of `"classic"`, `"bw"`,
#'   `"minimal"`, or `"gray"`.
#'
#' @return A list containing plotting data, individual plots,
#'   and the combined plot.
#' @examples
#' data(spe_example)
#'
#' spe_qc <- add_qcs(
#'   spe_example,
#'   assay_name = "counts",
#'   mito_pattern = "^MT-"
#' )
#'
#' p_qc <- plot_qc(
#'   spe_qc,
#'   bins = 45,
#'   show_density = TRUE,
#'   theme_name = "classic"
#' )
#'
#' p_qc$plot
#' @export
plot_qc <- function(
  spe,
  bins = 45,
  show_density = TRUE,
  theme_name = "classic"
) {
  # Check QC metrics


  required_spot <- c(
    "log_library_size",
    "detected_genes",
    "mito_fraction"
  )

  required_gene <- c(
    "log_gene_mean"
  )


  if (
    !all(
      required_spot %in%
        colnames(
          SummarizedExperiment::colData(spe)
        )
    )
  ) {
    stop(
      "QC metrics were not found. ",
      "Run add_qcs() first."
    )
  }


  if (
    !all(
      required_gene %in%
        colnames(
          SummarizedExperiment::rowData(spe)
        )
    )
  ) {
    stop(
      "Gene-level QC metrics were not found. ",
      "Run add_qcs() first."
    )
  }


  # Data


  qc_df <-
    as.data.frame(
      SummarizedExperiment::colData(spe)
    )


  gene_df <-
    as.data.frame(
      SummarizedExperiment::rowData(spe)
    )


  # Plot helper


  .qc_hist <- function(data,
                       variable,
                       x_label,
                       title,
                       fill) {
    p <- ggplot2::ggplot(
      data,
      ggplot2::aes(
        x = .data[[variable]]
      )
    ) +
      ggplot2::geom_histogram(
        bins = bins,
        fill = fill,
        colour = "white",
        linewidth = 0.3,
        alpha = 0.85
      )

    p +

      ggplot2::labs(
        x = x_label,
        y = "Frequency",
        title = title
      ) +

      .get_plot_theme(
        theme_name
      ) +

      ggplot2::theme(
        panel.grid =
          ggplot2::element_blank(),
        plot.title =
          ggplot2::element_text(
            face = "bold",
            size = 11
          )
      )
  }


  # Library size

  p_library <- .qc_hist(
    qc_df,
    "log_library_size",
    "Log library size",
    "Library size",
    "#4C78A8"
  )


  # Gene expression

  p_gene <- .qc_hist(
    gene_df,
    "log_gene_mean",
    "Log mean count per gene",
    "Gene expression",
    "#59A14F"
  )


  # Detected genes

  p_detected <- .qc_hist(
    qc_df,
    "detected_genes",
    "Detected genes",
    "Detected genes per spot",
    "#F28E2B"
  )


  # Mitochondrial proportion

  p_mito <- .qc_hist(
    qc_df,
    "mito_fraction",
    "Mitochondrial proportion",
    "Mitochondrial fraction",
    "#E15759"
  )


  # Combine


  p <- patchwork::wrap_plots(
    list(
      p_library,
      p_gene,
      p_detected,
      p_mito
    ),
    ncol = 2
  )


  return(
    list(
      data = list(
        spots = qc_df,
        genes = gene_df
      ),
      plots = list(
        library_size = p_library,
        gene_mean = p_gene,
        detected_genes = p_detected,
        mitochondrial = p_mito
      ),
      plot = p
    )
  )
}


#' Plot QC cutoff effects
#'
#' Show how different QC cutoff values affect the proportion
#' of spots and genes that would be removed.
#'
#' No filtering is performed by this function.
#'
#' @param spe A SpatialExperiment object containing QC metrics
#'   generated by `add_qcs()`.
#' @param library_cutoff Optional selected cutoff for log
#'   library size.
#' @param gene_cutoff Optional selected cutoff for log mean
#'   gene expression.
#' @param n_points Number of cutoff values used to construct
#'   each curve. Default is 200.
#' @param theme_name Plot theme. One of `"classic"`, `"bw"`,
#'   `"minimal"`, or `"gray"`.
#'
#' @return A list containing cutoff data and plot.
#' @examples
#' data(spe_example)
#'
#' spe_qc <- add_qcs(
#'   spe_example,
#'   assay_name = "counts",
#'   mito_pattern = "^MT-"
#' )
#'
#' ls <- c(100, 200)
#' gc <- c(20, 50)
#'
#' p <- lapply(seq_len(2), function(i) {
#'   p_cutoffs <- plot_qc_cutoffs(
#'     spe_qc,
#'     library_cutoff = ls[i],
#'     gene_cutoff = gc[i],
#'     n_points = 200,
#'     theme_name = "classic"
#'   )
#'
#'   p_cutoffs$plot
#' })
#'
#' patchwork::wrap_plots(p, ncol = 1) +
#'   patchwork::plot_annotation(tag_levels = "A")
#' @export
plot_qc_cutoffs <- function(
  spe,
  library_cutoff = NULL,
  gene_cutoff = NULL,
  n_points = 200,
  theme_name = "classic"
) {
  # Check QC metrics


  if (
    !"log_library_size" %in%
      colnames(
        SummarizedExperiment::colData(spe)
      ) ||
      !"log_gene_mean" %in%
        colnames(
          SummarizedExperiment::rowData(spe)
        )
  ) {
    stop(
      "QC metrics were not found. ",
      "Run add_qcs() first."
    )
  }


  # Library-size cutoffs


  library_cutoffs <- seq(
    min(
      spe$log_library_size,
      na.rm = TRUE
    ),
    max(
      spe$log_library_size,
      na.rm = TRUE
    ),
    length.out = n_points
  )


  # Gene-expression cutoffs


  log_gene_mean <-
    SummarizedExperiment::rowData(
      spe
    )$log_gene_mean


  gene_cutoffs <- seq(
    min(
      log_gene_mean,
      na.rm = TRUE
    ),
    max(
      log_gene_mean,
      na.rm = TRUE
    ),
    length.out = n_points
  )


  # Spot removal


  df_spots <- data.frame(
    cutoff = library_cutoffs,
    removed = vapply(
      library_cutoffs,
      function(x) {
        mean(
          spe$log_library_size < x,
          na.rm = TRUE
        )
      },
      numeric(1)
    ),
    type = "Spots"
  )


  # Gene removal


  df_genes <- data.frame(
    cutoff = gene_cutoffs,
    removed = vapply(
      gene_cutoffs,
      function(x) {
        mean(
          log_gene_mean < x,
          na.rm = TRUE
        )
      },
      numeric(1)
    ),
    type = "Genes"
  )


  # Combine


  df <- dplyr::bind_rows(
    df_spots,
    df_genes
  )


  # Selected cutoffs


  selected <- data.frame(
    type = character(),
    cutoff = numeric(),
    removed = numeric()
  )


  if (!is.null(library_cutoff)) {
    removed_spots <- mean(
      spe$log_library_size < library_cutoff,
      na.rm = TRUE
    )

    selected <- rbind(
      selected,
      data.frame(
        type = "Spots",
        cutoff = library_cutoff,
        removed = removed_spots
      )
    )
  }


  if (!is.null(gene_cutoff)) {
    removed_genes <- mean(
      log_gene_mean < gene_cutoff,
      na.rm = TRUE
    )

    selected <- rbind(
      selected,
      data.frame(
        type = "Genes",
        cutoff = gene_cutoff,
        removed = removed_genes
      )
    )
  }


  # Plot


  p_genes <- ggplot2::ggplot(
    dplyr::filter(df, type == "Genes"),
    ggplot2::aes(x = cutoff, y = removed)
  ) +
    ggplot2::geom_area(
      fill = "grey85",
      alpha = 0.6
    ) +
    ggplot2::geom_line(
      colour = "#3B6FB6",
      linewidth = 1.1
    ) +
    ggplot2::scale_y_continuous(
      labels = scales::label_percent(accuracy = 1)
    ) +
    ggplot2::labs(
      title = "Genes",
      x = "Log mean gene expression",
      y = "Proportion removed"
    ) +
    .get_plot_theme(theme_name)


  p_spots <- ggplot2::ggplot(
    dplyr::filter(df, type == "Spots"),
    ggplot2::aes(x = cutoff, y = removed)
  ) +
    ggplot2::geom_area(
      fill = "grey85",
      alpha = 0.6
    ) +
    ggplot2::geom_line(
      colour = "#3B6FB6",
      linewidth = 1.1
    ) +
    ggplot2::scale_y_continuous(
      labels = scales::label_percent(accuracy = 1)
    ) +
    ggplot2::labs(
      title = "Spots",
      x = "Log library size",
      y = NULL
    ) +
    .get_plot_theme(theme_name)


  # Add selected cutoff lines and points


  add_cutoff <- function(p, selected, type) {
    cutoff_df <- dplyr::filter(
      selected,
      .data$type == .env$type
    )
    if (nrow(cutoff_df) == 0) {
      return(p)
    }

    p +
      ggplot2::geom_vline(
        data = cutoff_df,
        ggplot2::aes(
          xintercept = .data$cutoff
        ),
        linetype = "dashed",
        linewidth = 0.8,
        colour = "#D62728"
      ) +
      ggplot2::geom_hline(
        data = cutoff_df,
        ggplot2::aes(
          yintercept = .data$removed
        ),
        linetype = "dashed",
        linewidth = 0.8,
        colour = "#D62728"
      ) +
      ggplot2::geom_point(
        data = cutoff_df,
        ggplot2::aes(
          x = .data$cutoff,
          y = .data$removed
        ),
        size = 3,
        colour = "#D62728"
      )
  }


  p_genes <- add_cutoff(
    p_genes,
    selected,
    "Genes"
  )

  p_spots <- add_cutoff(
    p_spots,
    selected,
    "Spots"
  )


  # Combine plots


  p <- patchwork::wrap_plots(
    p_genes,
    p_spots,
    ncol = 2
  )


  return(
    list(
      data = df,
      selected = selected,
      plot = p
    )
  )
}


# Quality-control filtering


#' Filter a SpatialExperiment using QC thresholds
#'
#' Filter spatial locations using log library size and genes
#' using log mean expression.
#'
#' QC metrics must first be calculated using
#' `add_qcs()`.
#'
#' @param spe A SpatialExperiment object containing QC metrics.
#' @param library_cutoff Optional minimum log library size.
#' @param gene_cutoff Optional minimum log mean gene expression.
#' @param recalculate Logical. If TRUE, QC metrics are
#'   recalculated after filtering. Default is TRUE.
#' @param assay_name Name of assay containing raw counts.
#'   Default is `"counts"`.
#' @param mito_pattern Regular expression identifying
#'   mitochondrial genes. Default is `"^MT-"`.
#'
#' @return A filtered SpatialExperiment object.
#' @examples
#' data(spe_example)
#' spe_qc <- add_qcs(
#'   spe_example,
#'   assay_name = "counts",
#'   mito_pattern = "^MT-"
#' )
#' spe_filtered <- filter_qc(
#'   spe_qc,
#'   library_cutoff = 4.5,
#'   gene_cutoff = 0.1,
#'   recalculate = TRUE,
#'   assay_name = "counts",
#'   mito_pattern = "^MT-"
#' )
#' @export
filter_qc <- function(
  spe,
  library_cutoff = NULL,
  gene_cutoff = NULL,
  recalculate = TRUE,
  assay_name = "counts",
  mito_pattern = "^MT-"
) {
  # Check QC metrics


  if (
    !"log_library_size" %in%
      colnames(
        SummarizedExperiment::colData(spe)
      ) ||
      !"log_gene_mean" %in%
        colnames(
          SummarizedExperiment::rowData(spe)
        )
  ) {
    stop(
      "QC metrics were not found. ",
      "Run add_qcs() first."
    )
  }


  # Spot filter


  if (is.null(library_cutoff)) {
    keep_spots <- rep(
      TRUE,
      ncol(spe)
    )
  } else {
    keep_spots <-
      spe$log_library_size >=
        library_cutoff
  }


  # Gene filter


  if (is.null(gene_cutoff)) {
    keep_genes <- rep(
      TRUE,
      nrow(spe)
    )
  } else {
    keep_genes <-
      SummarizedExperiment::rowData(
        spe
      )$log_gene_mean >=
        gene_cutoff
  }


  # Filter


  spe_filtered <- spe[
    keep_genes,
    keep_spots
  ]


  # Recalculate QC metrics


  if (recalculate) {
    spe_filtered <- add_qcs(
      spe_filtered,
      assay_name = assay_name,
      mito_pattern = mito_pattern
    )
  }


  return(spe_filtered)
}


#' Plot Spatial Distribution of Removed QC Spots
#'
#' Visualises the spatial locations of spots retained and removed
#' after quality control filtering. Retained spots are shown in
#' blue, while removed spots are shown in red.
#'
#' @param spe Original SpatialExperiment object before QC filtering.
#' @param spe_filtered SpatialExperiment object after QC filtering.
#' @param point_size Numeric. Size of the plotted spots.
#'   Default is 0.8.
#' @param theme_name Character. Plot theme supported by
#'   `.get_plot_theme()`. Default is "classic".
#'
#' @return A ggplot object showing the spatial distribution of
#'   retained and removed spots.
#'
#' @details
#' Spots are classified by comparing their column names in the
#' original and filtered SpatialExperiment objects. All spatial
#' coordinates are obtained from the original object.
#'
#' This function helps identify whether QC filtering removes
#' spots from particular spatial regions.
#'
#' @examples
#' data(spe_example)
#'
#' spe_qc <- add_qcs(
#'   spe_example,
#'   assay_name = "counts",
#'   mito_pattern = "^MT-"
#' )
#'
#' p_cutoffs <- plot_qc_cutoffs(
#'   spe_qc,
#'   library_cutoff = 3.5,
#'   gene_cutoff = 0.2,
#'   n_points = 200,
#'   theme_name = "classic"
#' )
#'
#' p_cutoffs$plot
#'
#' @export
plot_qc_removed_spots <- function(
  spe,
  spe_filtered,
  point_size = 0.8,
  theme_name = "classic"
) {
  # Validate input objects

  if (
    !inherits(spe, "SpatialExperiment") ||
      !inherits(spe_filtered, "SpatialExperiment")
  ) {
    stop(
      "Both inputs must be SpatialExperiment objects.",
      call. = FALSE
    )
  }

  # Validate spot identifiers

  original_ids <- colnames(spe)
  filtered_ids <- colnames(spe_filtered)

  if (
    is.null(original_ids) ||
      is.null(filtered_ids) ||
      anyNA(original_ids) ||
      anyNA(filtered_ids) ||
      anyDuplicated(original_ids) ||
      anyDuplicated(filtered_ids)
  ) {
    stop(
      "Both objects must have unique, non-missing spot IDs.",
      call. = FALSE
    )
  }

  if (!all(filtered_ids %in% original_ids)) {
    stop(
      "spe_filtered contains spots not present in spe.",
      call. = FALSE
    )
  }

  if (
    !is.numeric(point_size) ||
      length(point_size) != 1L ||
      !is.finite(point_size) ||
      point_size <= 0
  ) {
    stop(
      "point_size must be a positive number.",
      call. = FALSE
    )
  }

  # Extract spatial coordinates

  coords <- SpatialExperiment::spatialCoords(spe)

  if (
    ncol(coords) < 2L ||
      nrow(coords) != ncol(spe)
  ) {
    stop(
      "Valid two-dimensional spatial coordinates are required.",
      call. = FALSE
    )
  }

  # Identify removed and retained spots

  status <- ifelse(
    original_ids %in% filtered_ids,
    "Retained",
    "Removed"
  )

  # Prepare plotting data

  plot_df <- data.frame(
    x = coords[, 1],
    y = coords[, 2],
    status = factor(
      status,
      levels = c("Retained", "Removed")
    )
  )

  # Calculate QC summary

  n_total <- ncol(spe)
  n_retained <- length(filtered_ids)
  n_removed <- n_total - n_retained

  pct_removed <- round(
    100 * n_removed / n_total,
    1
  )

  # Plot

  p <- ggplot2::ggplot(
    plot_df,
    ggplot2::aes(
      x = .data$x,
      y = .data$y,
      colour = .data$status
    )
  ) +
    ggplot2::geom_point(
      size = point_size,
      alpha = 0.85
    ) +
    ggplot2::scale_colour_manual(
      values = c(
        "Retained" = "#4C78A8",
        "Removed" = "#E15759"
      ),
      drop = FALSE
    ) +
    ggplot2::coord_fixed() +
    ggplot2::labs(
      title = "Spatial distribution map of QC-filtered cells",
      subtitle = paste0(
        n_removed,
        " of ",
        n_total,
        " spots removed (",
        pct_removed,
        "%)"
      ),
      x = "X",
      y = "Y",
      colour = "QC status"
    ) +
    .get_plot_theme(theme_name) +
    ggplot2::theme(
      panel.grid = ggplot2::element_blank(),
      plot.title = ggplot2::element_text(
        face = "bold",
        size = 11
      )
    )

  return(p)
}
