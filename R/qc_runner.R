#' Plot quality-control distributions
#'
#' Plot distributions of the main spot-level and gene-level
#' QC metrics stored in a SpatialExperiment object.
#'
#' The function can be used before or after filtering.
#'
#' @param spe A SpatialExperiment object containing QC metrics
#'   generated by `add_qc_metrics()`.
#' @param bins Number of histogram bins. Default is 45.
#' @param show_density Logical. If TRUE, density curves are
#'   added to the histograms.
#' @param theme_name Plot theme. One of `"classic"`, `"bw"`,
#'   `"minimal"`, or `"gray"`.
#'
#' @return A list containing plotting data, individual plots,
#'   and the combined plot.
#'
#' @export
plot_qc <- function(
    spe,
    bins = 45,
    show_density = TRUE,
    theme_name = "classic"
) {

  # ----------------------------------------------------------
  # Check QC metrics
  # ----------------------------------------------------------

  required_spot <- c(
    "log_library_size",
    "detected_genes",
    "mito_fraction"
  )

  required_gene <- c(
    "log_gene_mean"
  )


  if (
    !all(
      required_spot %in%
      colnames(
        SummarizedExperiment::colData(spe)
      )
    )
  ) {

    stop(
      "QC metrics were not found. ",
      "Run add_qc_metrics() first."
    )
  }


  if (
    !all(
      required_gene %in%
      colnames(
        SummarizedExperiment::rowData(spe)
      )
    )
  ) {

    stop(
      "Gene-level QC metrics were not found. ",
      "Run add_qc_metrics() first."
    )
  }


  # ----------------------------------------------------------
  # Data
  # ----------------------------------------------------------

  qc_df <-
    as.data.frame(
      SummarizedExperiment::colData(spe)
    )


  gene_df <-
    as.data.frame(
      SummarizedExperiment::rowData(spe)
    )


  # ----------------------------------------------------------
  # Plot helper
  # ----------------------------------------------------------

  .qc_hist <- function(
    data,
    variable,
    x_label,
    title,
    fill,
    line_colour
  ) {

    p <- ggplot2::ggplot(
      data,
      ggplot2::aes(
        x = .data[[variable]]
      )
    ) +

      ggplot2::geom_histogram(
        ggplot2::aes(
          y = ggplot2::after_stat(
            density
          )
        ),
        bins = bins,
        fill = fill,
        colour = "white",
        linewidth = 0.3,
        alpha = 0.85
      )


    if (show_density) {

      p <- p +

        ggplot2::geom_density(
          colour = line_colour,
          linewidth = 1
        )
    }


    p +

      ggplot2::labs(
        x = x_label,
        y = "Density",
        title = title
      ) +

      .get_plot_theme(
        theme_name
      ) +

      ggplot2::theme(

        panel.grid =
          ggplot2::element_blank(),

        plot.title =
          ggplot2::element_text(
            face = "bold",
            size = 11
          )
      )
  }


  # ----------------------------------------------------------
  # Library size
  # ----------------------------------------------------------

  p_library <- .qc_hist(
    qc_df,
    "log_library_size",
    "Log library size",
    "Library size",
    "#4C78A8",
    "#1F3A5F"
  )


  # ----------------------------------------------------------
  # Gene expression
  # ----------------------------------------------------------

  p_gene <- .qc_hist(
    gene_df,
    "log_gene_mean",
    "Log mean count per gene",
    "Gene expression",
    "#59A14F",
    "#2F6130"
  )


  # ----------------------------------------------------------
  # Detected genes
  # ----------------------------------------------------------

  p_detected <- .qc_hist(
    qc_df,
    "detected_genes",
    "Detected genes",
    "Detected genes per spot",
    "#F28E2B",
    "#A85B12"
  )


  # ----------------------------------------------------------
  # Mitochondrial proportion
  # ----------------------------------------------------------

  p_mito <- .qc_hist(
    qc_df,
    "mito_fraction",
    "Mitochondrial proportion",
    "Mitochondrial fraction",
    "#E15759",
    "#8E3032"
  )


  # ----------------------------------------------------------
  # Combine
  # ----------------------------------------------------------

  p <- patchwork::wrap_plots(
    list(
      p_library,
      p_gene,
      p_detected,
      p_mito
    ),
    ncol = 2
  )


  return(
    list(

      data = list(
        spots = qc_df,
        genes = gene_df
      ),

      plots = list(
        library_size = p_library,
        gene_mean = p_gene,
        detected_genes = p_detected,
        mitochondrial = p_mito
      ),

      plot = p
    )
  )
}



