#' Plot QC cutoff effects
#'
#' Show how different QC cutoff values affect the proportion
#' of spots and genes that would be removed.
#'
#' No filtering is performed by this function.
#'
#' @param spe A SpatialExperiment object containing QC metrics
#'   generated by `add_qc_metrics()`.
#' @param library_cutoff Optional selected cutoff for log
#'   library size.
#' @param gene_cutoff Optional selected cutoff for log mean
#'   gene expression.
#' @param n_points Number of cutoff values used to construct
#'   each curve. Default is 200.
#' @param theme_name Plot theme. One of `"classic"`, `"bw"`,
#'   `"minimal"`, or `"gray"`.
#'
#' @return A list containing cutoff data and plot.
#'
#' @export
plot_qc_cutoffs <- function(
    spe,
    library_cutoff = NULL,
    gene_cutoff = NULL,
    n_points = 200,
    theme_name = "classic"
) {

  # ----------------------------------------------------------
  # Check QC metrics
  # ----------------------------------------------------------

  if (
    !"log_library_size" %in%
    colnames(
      SummarizedExperiment::colData(spe)
    ) ||
    !"log_gene_mean" %in%
    colnames(
      SummarizedExperiment::rowData(spe)
    )
  ) {

    stop(
      "QC metrics were not found. ",
      "Run add_qc_metrics() first."
    )
  }


  # ----------------------------------------------------------
  # Library-size cutoffs
  # ----------------------------------------------------------

  library_cutoffs <- seq(
    min(
      spe$log_library_size,
      na.rm = TRUE
    ),
    max(
      spe$log_library_size,
      na.rm = TRUE
    ),
    length.out = n_points
  )


  # ----------------------------------------------------------
  # Gene-expression cutoffs
  # ----------------------------------------------------------

  log_gene_mean <-
    SummarizedExperiment::rowData(
      spe
    )$log_gene_mean


  gene_cutoffs <- seq(
    min(
      log_gene_mean,
      na.rm = TRUE
    ),
    max(
      log_gene_mean,
      na.rm = TRUE
    ),
    length.out = n_points
  )


  # ----------------------------------------------------------
  # Spot removal
  # ----------------------------------------------------------

  df_spots <- data.frame(

    cutoff = library_cutoffs,

    removed = vapply(
      library_cutoffs,
      function(x) {

        mean(
          spe$log_library_size < x,
          na.rm = TRUE
        )
      },
      numeric(1)
    ),

    type = "Spots"
  )


  # ----------------------------------------------------------
  # Gene removal
  # ----------------------------------------------------------

  df_genes <- data.frame(

    cutoff = gene_cutoffs,

    removed = vapply(
      gene_cutoffs,
      function(x) {

        mean(
          log_gene_mean < x,
          na.rm = TRUE
        )
      },
      numeric(1)
    ),

    type = "Genes"
  )


  # ----------------------------------------------------------
  # Combine
  # ----------------------------------------------------------

  df <- dplyr::bind_rows(
    df_spots,
    df_genes
  )


  # ----------------------------------------------------------
  # Plot
  # ----------------------------------------------------------

  p <- ggplot2::ggplot(
    df,
    ggplot2::aes(
      x = .data$cutoff,
      y = .data$removed
    )
  ) +

    ggplot2::geom_area(
      fill = "grey85",
      alpha = 0.6
    ) +

    ggplot2::geom_line(
      colour = "#3B6FB6",
      linewidth = 1.1
    ) +

    ggplot2::facet_wrap(
      ~ type,
      scales = "free_x"
    ) +

    ggplot2::scale_y_continuous(
      labels =
        scales::label_percent(
          accuracy = 1
        )
    ) +

    ggplot2::labs(
      x = "Cutoff value",
      y = "Proportion removed"
    ) +

    .get_plot_theme(
      theme_name
    ) +

    ggplot2::theme(

      panel.grid =
        ggplot2::element_blank(),

      strip.background =
        ggplot2::element_blank(),

      strip.text =
        ggplot2::element_text(
          face = "bold"
        )
    )


  # ----------------------------------------------------------
  # Selected cutoffs
  # ----------------------------------------------------------

  selected <- data.frame(
    type = character(),
    cutoff = numeric(),
    removed = numeric()
  )


  if (!is.null(library_cutoff)) {

    removed_spots <- mean(
      spe$log_library_size < library_cutoff,
      na.rm = TRUE
    )

    selected <- rbind(
      selected,
      data.frame(
        type = "Spots",
        cutoff = library_cutoff,
        removed = removed_spots
      )
    )
  }


  if (!is.null(gene_cutoff)) {

    removed_genes <- mean(
      log_gene_mean < gene_cutoff,
      na.rm = TRUE
    )

    selected <- rbind(
      selected,
      data.frame(
        type = "Genes",
        cutoff = gene_cutoff,
        removed = removed_genes
      )
    )
  }


  # ----------------------------------------------------------
  # Add selected cutoff lines and point
  # ----------------------------------------------------------

  if (nrow(selected) > 0) {

    p <- p +

      ggplot2::geom_vline(
        data = selected,
        ggplot2::aes(
          xintercept = .data$cutoff
        ),
        linetype = "dashed",
        linewidth = 0.8,
        colour = "#D62728"
      ) +

      ggplot2::geom_hline(
        data = selected,
        ggplot2::aes(
          yintercept = .data$removed
        ),
        linetype = "dashed",
        linewidth = 0.8,
        colour = "#D62728"
      ) +

      ggplot2::geom_point(
        data = selected,
        ggplot2::aes(
          x = .data$cutoff,
          y = .data$removed
        ),
        size = 3,
        colour = "#D62728"
      )
  }

  return(
    list(
      data = df,
      selected = selected,
      plot = p
    )
  )
}




